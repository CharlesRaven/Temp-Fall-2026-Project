CREATE TABLE degree_program (
    program_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    degree_type VARCHAR(10) NOT NULL CHECK (degree_type IN ('AS', 'BAS')),
    required_credits INTEGER NOT NULL CHECK (required_credits > 0)
);

CREATE TABLE app_user (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_id INTEGER REFERENCES degree_program(program_id) ON DELETE RESTRICT,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE CHECK (email = lower(btrim(email))),
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(12) NOT NULL DEFAULT 'STUDENT'
        CHECK (role IN ('STUDENT', 'ADVISOR', 'PROFESSOR'))
);
CREATE INDEX ix_app_user_program_id ON app_user(program_id);
