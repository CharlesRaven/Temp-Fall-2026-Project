-- Creates tables for courses and their prerequisites.
CREATE TABLE course (
    course_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_code VARCHAR(20) NOT NULL UNIQUE,
    title VARCHAR(200) NOT NULL,
    credit_hours INTEGER NOT NULL CHECK (credit_hours > 0),
    description TEXT,
    CHECK (course_code = upper(replace(btrim(course_code), ' ', '')))
);

CREATE TABLE course_prerequisite (
    course_id INTEGER NOT NULL REFERENCES course(course_id) ON DELETE RESTRICT,
    prerequisite_course_id INTEGER NOT NULL REFERENCES course(course_id) ON DELETE RESTRICT,
    PRIMARY KEY (course_id, prerequisite_course_id),
    CHECK (course_id <> prerequisite_course_id)
);

CREATE INDEX ix_course_prerequisite_prerequisite_course_id
    ON course_prerequisite(prerequisite_course_id);
